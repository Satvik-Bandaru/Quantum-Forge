import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('QUBO triangle benchmark preserves executed evidence through edits, export and history',async({page})=>{
 await page.setViewportSize({width:1600,height:1000});
 await page.goto('/');
 await page.getByRole('button',{name:'QUBO Lab',exact:true}).click();
 await page.getByRole('button',{name:'Triangle Max-Cut',exact:true}).click();
 await expect(page.getByTestId('qubo-couplings')).toContainText('Derived from setup');
 await expect(page.getByTestId('qubo-empty')).toBeVisible();
 await page.getByRole('button',{name:'Run QUBO benchmark',exact:true}).click();
 await expect(page.getByTestId('qubo-comparison')).toBeVisible({timeout:60000});
 await expect(page.getByTestId('qubo-exact-energy')).toHaveText('−2');
 await expect(page.getByTestId('qubo-comparison').locator('tbody tr')).toHaveCount(5);
 await expect(page.getByTestId('qubo-comparison')).toContainText('QAOA');
 await expect(page.getByTestId('qubo-comparison')).toContainText('Ocean');
 await expect(page.getByTestId('qubo-trace')).toContainText('Actual objective evaluations');
 await expect(page.getByTestId('qubo-trace').getByText('Exact minimum',{exact:true})).toBeVisible();
 const firstId=await page.getByTestId('qubo-run-id').innerText();
 await page.getByRole('button',{name:'Open learning guide',exact:true}).click();
 await page.getByRole('button',{name:'Interpret this result',exact:true}).click();
 await expect(page.locator('.guide-answer')).toContainText('exact minimum is -2');
 await page.getByLabel('Q 0 0', {exact:true}).fill('-3');
 await expect(page.getByTestId('qubo-stale')).toBeVisible();
 await expect(page.getByTestId('qubo-exact-energy')).toHaveText('−2');
 await page.getByRole('button',{name:'Run QUBO benchmark',exact:true}).click();
 await expect(page.getByTestId('qubo-stale')).toHaveCount(0,{timeout:60000});
 await expect(page.getByTestId('qubo-exact-energy')).toHaveText('−3');
 await expect(page.locator('.guide-answer')).not.toContainText('exact minimum is -2');
 await page.getByRole('button',{name:'Interpret this result',exact:true}).click();
 await expect(page.locator('.guide-answer')).toContainText('exact minimum is -3');
 await page.getByRole('button',{name:'Close learning guide',exact:true}).click();
 const currentId=await page.getByTestId('qubo-run-id').innerText();
 expect(currentId).not.toBe(firstId);
 const download=page.waitForEvent('download');
 await page.getByRole('link',{name:'Run CSV',exact:true}).click();
 const file=await download;
 expect(file.suggestedFilename()).toMatch(/\.csv$/);
 const csv=await readFile((await file.path())!,'utf8');
 expect(csv).toContain('energy,gap,expected_energy');
 expect(csv).toContain('qaoa');
 expect(csv).toContain('"matrix"');
 await page.getByRole('button',{name:'History',exact:true}).click();
 await page.getByRole('button',{name:'Open experiment'}).first().click();
 await expect(page.getByRole('heading',{name:'QUBO Model Builder',exact:true})).toBeVisible();
 await expect(page.getByTestId('qubo-run-id')).toHaveText(currentId);
 await page.screenshot({path:'../docs/screenshots/qubo-lab-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Triangle Max-Cut',exact:true}).click();
 await expect(page.getByTestId('qubo-stale')).toBeVisible();
 await expect(page.getByTestId('qubo-exact-energy')).toHaveText('−3');
});

test('QUBO validates JSON, derives Ising coefficients, and fits mobile',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'QUBO Lab',exact:true}).click();
 await page.getByRole('button',{name:'One-hot assignment',exact:true}).click();
 await expect(page.getByLabel('Energy offset',{exact:true})).toHaveValue('4');
 await page.getByRole('button',{name:'Import model JSON',exact:true}).click();
 await page.getByLabel('QUBO model JSON', {exact:true}).fill('{"matrix":[[0,1],[1,0]],"offset":0}');
 await page.getByRole('button',{name:'Apply JSON',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('lower triangle');
 await page.getByLabel('QUBO model JSON', {exact:true}).fill('{"matrix":[[-2,2],[0,-2]]}');
 await page.getByRole('button',{name:'Apply JSON',exact:true}).click();
 await expect(page.getByLabel('Q 0 0', {exact:true})).toHaveValue('-2');
 await expect(page.getByLabel('Energy offset',{exact:true})).toHaveValue('0');
 await page.getByRole('button',{name:'Inspect variable x0',exact:true}).click();
 await expect(page.getByTestId('qubo-coefficient-detail')).toContainText('0.5');
 await page.getByLabel('Binary variables',{exact:true}).selectOption('5');
 await page.getByLabel('Q 0 4',{exact:true}).fill('2');
 await page.getByRole('button',{name:'Inspect coupling x0 x4',exact:true}).click();
 await expect(page.getByTestId('qubo-coefficient-detail')).toContainText('x4');
 await page.getByLabel('Binary variables',{exact:true}).selectOption('2');
 await expect(page.getByTestId('qubo-coefficient-detail')).toContainText('Variable x0');
 await expect(page.getByTestId('qubo-coefficient-detail')).not.toContainText('x4');
 await page.getByLabel('Q 0 0',{exact:true}).fill('');
 await expect(page.getByTestId('qubo-couplings')).toContainText('Complete all coefficients');
 await page.getByRole('button',{name:'Run QUBO benchmark',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('Every coefficient must be finite');
 await page.getByLabel('Q 0 0',{exact:true}).fill('-2');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.screenshot({path:'../docs/screenshots/qubo-lab-mobile.png',fullPage:true});
});
